class stringConcat{
  public static void main(String[] args) {
    String str1 = "We are learning";
    String str2 = "Java.";
    int num = 123;
    String str3 = str1 + " " + str2;
    String str4 = str1 + num;
    System.out.println(str3);
    System.out.println(str4);
    System.out.println(str1);
  }
}
