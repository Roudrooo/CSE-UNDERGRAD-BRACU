"""# Model comparison

The predictors are industrial production, imports, foreign-exchange reserves,
the average exchange rate, and exports. GDP, inflation, and CPI are not used
as predictors for one another. This prevents a model from using one outcome
to predict another outcome in the same period.

The last two fiscal years are used as the test set so the evaluation reflects
the chronological order of the data.

Feature scaling by model family
--------------------------------
- Linear Regression, Decision Tree, XGBoost: use the original (unscaled) feature
  values. Tree-based models are scale-invariant, and unregularized OLS doesn't
  need scaling either.
- Ridge, Lasso, Elastic Net, KNN: use standardized features. Regularized linear
  models penalize coefficient magnitude, so features must be on a comparable
  scale or the penalty falls unevenly across predictors.

Choosing the regularization strength
-------------------------------------
With only a handful of training rows, a single held-out validation split isn't
reliable for picking alpha. RidgeCV / LassoCV / ElasticNetCV instead use
leave-one-out cross-validation *within the training fold only* to choose the
regularization strength, so the two test fiscal years are never used for tuning.
"""

targets = ["GDP", "Inflation_Rate", "CPI"]
feature_columns = ["TotalInd", "Imports", "Forex", "ExchAvg", "Exports"]
test_years = 2

if len(model_data) <= test_years + 3:
    raise ValueError("Not enough complete annual observations for the chosen train/test split.")

train_data = model_data.iloc[:-test_years]
test_data = model_data.iloc[-test_years:]

print("Training fiscal years:", train_data["FY_clean"].tolist())
print("Testing fiscal years:", test_data["FY_clean"].tolist())

X_train = train_data[feature_columns]
X_test = test_data[feature_columns]

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# A grid of candidate regularization strengths for the CV-based linear models.
ALPHA_GRID = np.logspace(-3, 3, 50)
loo = LeaveOneOut()

all_results = []

for target in targets:
    y_train = train_data[target]
    y_test = test_data[target]

    models = {
        "Linear Regression": (LinearRegression(), X_train, X_test),
        "Ridge (RidgeCV)": (
            RidgeCV(alphas=ALPHA_GRID, cv=loo),
            X_train_scaled,
            X_test_scaled,
        ),
        "Lasso (LassoCV)": (
            LassoCV(alphas=ALPHA_GRID, cv=loo, max_iter=20000, random_state=42),
            X_train_scaled,
            X_test_scaled,
        ),
        "Elastic Net (ElasticNetCV)": (
            ElasticNetCV(
                alphas=ALPHA_GRID,
                l1_ratio=[0.1, 0.3, 0.5, 0.7, 0.9, 0.95, 0.99, 1.0],
                cv=loo,
                max_iter=20000,
                random_state=42,
            ),
            X_train_scaled,
            X_test_scaled,
        ),
        "Decision Tree": (
            DecisionTreeRegressor(max_depth=3, random_state=42),
            X_train,
            X_test,
        ),
        "KNN (k=3)": (
            KNeighborsRegressor(n_neighbors=3),
            X_train_scaled,
            X_test_scaled,
        ),
    }

    if XGBOOST_AVAILABLE:
        # Small, heavily regularized settings: this dataset has very few rows,
        # so a shallow, slow-learning booster with few trees is used to avoid
        # trivially overfitting the training fold.
        models["XGBoost"] = (
            XGBRegressor(
                n_estimators=100,
                max_depth=2,
                learning_rate=0.05,
                subsample=0.8,
                colsample_bytree=0.8,
                reg_alpha=0.1,
                reg_lambda=1.0,
                random_state=42,
            ),
            X_train,
            X_test,
        )

    target_results = []
    for model_name, (model, training_features, testing_features) in models.items():
        model.fit(training_features, y_train)
        predictions = model.predict(testing_features)

        result_row = {
            "Target": target,
            "Model": model_name,
            "MAE": mean_absolute_error(y_test, predictions),
            "RMSE": np.sqrt(mean_squared_error(y_test, predictions)),
            "R2": r2_score(y_test, predictions),
        }
        # Record the chosen regularization strength for the CV-tuned models.
        if hasattr(model, "alpha_"):
            result_row["Chosen_Alpha"] = model.alpha_
        if hasattr(model, "l1_ratio_"):
            result_row["Chosen_L1_Ratio"] = model.l1_ratio_

        target_results.append(result_row)

    target_results = pd.DataFrame(target_results)
    all_results.append(target_results)

    print(f"\nResults for {target}")
    display(target_results.round(3))

    plt.figure(figsize=(9, 4))
    plt.bar(target_results["Model"], target_results["R2"], color="tab:blue")
    plt.title(f"R² Comparison: {target}")
    plt.xlabel("Model")
    plt.ylabel("R² on last two fiscal years")
    plt.xticks(rotation=30, ha="right")
    plt.grid(axis="y", alpha=0.3)
    plt.tight_layout()
    plt.show()

model_results = pd.concat(all_results, ignore_index=True)
print("Combined model results")
display(model_results.round(3))

"""## 12. Feature importance / coefficients (regularized models)

Lasso and Elastic Net can zero out coefficients entirely, which is a useful
read on which predictors each target actually relies on with this small
feature set.
"""

for target in targets:
    y_train = train_data[target]

    lasso_final = LassoCV(alphas=ALPHA_GRID, cv=loo, max_iter=20000, random_state=42)
    lasso_final.fit(X_train_scaled, y_train)

    coef_table = pd.DataFrame(
        {"Feature": feature_columns, "Lasso_Coefficient": lasso_final.coef_}
    ).sort_values("Lasso_Coefficient", key=np.abs, ascending=False)

    print(f"\nLasso coefficients for {target} (alpha={lasso_final.alpha_:.4f})")
    display(coef_table)

